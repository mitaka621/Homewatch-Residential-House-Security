using System.Diagnostics;
using System.Net.NetworkInformation;
using System.Text;

const string blazorAppCertificatePath = @"..\..\..\..\..\Homewatch\Homewatch\server.pfx";
const string blazorAppEnvironmentFileRelativePath = @"..\..\..\..\..\Homewatch\Homewatch\.env";
const string blazorAppEnvironmentExampleFileRelativePath = @"..\..\..\..\..\Homewatch\Homewatch\.env.example";
const string certificatePasswordEnvironmentKey = "CertificatesConfig__CertificateAutoGeneratedPassword";
const string repositoryRootRelativePath = @"..\..\..\..\..";

string opensslPath = GetOpenSslPath();

if (!IsOpenSslAvailable(opensslPath))
{
    Console.WriteLine("\nBundled OpenSSL was not found.");
    Console.WriteLine($"Expected location: {opensslPath}");
    Console.WriteLine("Rebuild the CertGenerator project to restore the bundled OpenSSL binaries.");

    Console.ReadLine();
    return;
}

Console.WriteLine($"OpenSSL is available at: {opensslPath}");

List<string> localIPs = GetLocalIPAddresses();
Console.WriteLine($"Local IPs detected: {string.Join(", ", localIPs)}");

string caKey = "ca.key";
string caCert = "ca.crt";
string serverKey = "server.key";
string serverCsr = "server.csr";
string serverCert = "server.crt";
string serverExt = "server.ext";
string pfxFile = "server.pfx";

string password = GenerateRandomPassword(16);

WriteServerExtensionsFile(serverExt, localIPs);

Console.WriteLine("Generating CA key and certificate...");
RunOpenSsl($"genrsa -out {caKey} 2048");
RunOpenSsl($"req -new -x509 -sha256 -days 3650 -key {caKey} -out {caCert} -subj \"/CN=MyLocalCA\"");

Console.WriteLine("Generating server key and CSR...");
RunOpenSsl($"genrsa -out {serverKey} 2048");
RunOpenSsl($"req -new -sha256 -key {serverKey} -out {serverCsr} -subj \"/CN=localhost\"");

Console.WriteLine("Signing server certificate with CA...");
RunOpenSsl($"x509 -req -sha256 -in {serverCsr} -CA {caCert} -CAkey {caKey} -CAcreateserial -out {serverCert} -days 825 -extfile {serverExt}");

Console.WriteLine("Exporting server certificate and key to PFX...");
RunOpenSsl($"pkcs12 -export -out {pfxFile} -inkey {serverKey} -in {serverCert} -certfile {caCert} -password pass:{password}");

Console.WriteLine($"PFX file generated: {pfxFile} with password: {password}");

CopyPfxToBlazorApp(pfxFile, blazorAppCertificatePath);

UpdateEnvironmentFileWithPassword(blazorAppEnvironmentFileRelativePath, blazorAppEnvironmentExampleFileRelativePath, password);

Console.WriteLine("Copied PFX to blazor app");

string caContent = File.ReadAllText(caCert);
string cString = ConvertToCString(caContent);

Console.WriteLine("Generated CA string for esp32:");
Console.WriteLine(cString);

UpdateAllFirmwareSecretsFiles(repositoryRootRelativePath, cString);

ImportCaToTrustedRoot(caCert);

Console.WriteLine($"\n\n====================================");

Console.WriteLine("Operation completed!");

Console.ReadLine();

string GetOpenSslPath()
{
    return Path.Combine(AppContext.BaseDirectory, "openssl", "win-x64", "openssl.exe");
}

bool IsOpenSslAvailable(string opensslExecutablePath)
{
    if (!File.Exists(opensslExecutablePath))
        return false;

    try
    {
        var process = new Process
        {
            StartInfo = new ProcessStartInfo
            {
                FileName = opensslExecutablePath,
                Arguments = "version",
                RedirectStandardOutput = true,
                UseShellExecute = false,
                CreateNoWindow = true,
            }
        };
        process.Start();
        process.WaitForExit();
        return process.ExitCode == 0;
    }
    catch
    {
        return false;
    }
}

List<string> GetLocalIPAddresses()
{
    var addresses = new List<string>();
    foreach (var ni in NetworkInterface.GetAllNetworkInterfaces())
    {
        if (ni.OperationalStatus == OperationalStatus.Up && ni.NetworkInterfaceType != NetworkInterfaceType.Loopback)
        {
            var props = ni.GetIPProperties();
            foreach (var addr in props.UnicastAddresses)
            {
                if (addr.Address.AddressFamily == System.Net.Sockets.AddressFamily.InterNetwork)
                {
                    string ip = addr.Address.ToString();
                    if (!addresses.Contains(ip))
                        addresses.Add(ip);
                }
            }
        }
    }
    return addresses;
}

void RunOpenSsl(string arguments)
{
    Console.WriteLine($"> openssl {arguments}");
    var process = new Process
    {
        StartInfo = new ProcessStartInfo
        {
            FileName = opensslPath,
            Arguments = arguments,
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            UseShellExecute = false,
            CreateNoWindow = true,
        }
    };
    process.Start();
    string output = process.StandardOutput.ReadToEnd();
    string error = process.StandardError.ReadToEnd();
    process.WaitForExit();

    if (!string.IsNullOrEmpty(output))
        Console.WriteLine(output);
    if (!string.IsNullOrEmpty(error))
        Console.WriteLine(error);

    if (process.ExitCode != 0)
        throw new Exception($"OpenSSL command failed: {arguments}");
}

void WriteServerExtensionsFile(string path, List<string> localIps)
{
    var sb = new StringBuilder();
    sb.Append("basicConstraints=CA:FALSE\n");
    sb.Append("keyUsage=digitalSignature,keyEncipherment\n");
    sb.Append("extendedKeyUsage=serverAuth\n");
    sb.Append("subjectAltName=@alt_names\n");
    sb.Append("\n");
    sb.Append("[alt_names]\n");

    sb.Append("DNS.1=localhost\n");
    int dnsIndex = 2;
    foreach (var ip in localIps)
    {
        sb.Append($"DNS.{dnsIndex}={ip}\n");
        dnsIndex++;
    }

    sb.Append("IP.1=127.0.0.1\n");
    sb.Append("IP.2=::1\n");
    int ipIndex = 3;
    foreach (var ip in localIps)
    {
        sb.Append($"IP.{ipIndex}={ip}\n");
        ipIndex++;
    }

    File.WriteAllText(path, sb.ToString());
}

string GenerateRandomPassword(int length)
{
    const string chars = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789";
    var sb = new StringBuilder();
    var rnd = new Random();
    for (int i = 0; i < length; i++)
        sb.Append(chars[rnd.Next(chars.Length)]);
    return sb.ToString();
}

string ConvertToCString(string text)
{
    var sb = new StringBuilder();
    sb.Append("#define ROOT_CA_CERT \\\n");
    using (var reader = new StringReader(text))
    {
        string? line;
        while ((line = reader.ReadLine()) != null)
        {
            sb.Append($"\"{line}\\n\" \\\n");
        }
    }
    return sb.ToString();
}

void CopyPfxToBlazorApp(string sourcePfx, string targetRelativePath)
{
    try
    {
        string currentDir = Directory.GetCurrentDirectory();
        string targetFullPath = Path.Combine(currentDir, targetRelativePath);

        Console.WriteLine($"\nCopying PFX to: {targetFullPath}");

        string? targetDir = Path.GetDirectoryName(targetFullPath);
        if (!Directory.Exists(targetDir) && targetDir != null)
        {
            Directory.CreateDirectory(targetDir);
        }

        File.Copy(sourcePfx, targetFullPath, overwrite: true);

        Console.WriteLine("PFX file successfully copied.");
    }
    catch (Exception ex)
    {
        Console.WriteLine($"Error copying PFX file: {ex.Message}");
    }
}

void UpdateEnvironmentFileWithPassword(string environmentFileRelativePath, string environmentExampleFileRelativePath, string password)
{
    try
    {
        string currentDir = Directory.GetCurrentDirectory();
        string environmentFileFullPath = Path.GetFullPath(Path.Combine(currentDir, environmentFileRelativePath));
        string environmentExampleFileFullPath = Path.GetFullPath(Path.Combine(currentDir, environmentExampleFileRelativePath));

        Console.WriteLine($"\nUpdating .env at: {environmentFileFullPath}");

        List<string> lines;

        if (File.Exists(environmentFileFullPath))
        {
            lines = File.ReadAllLines(environmentFileFullPath).ToList();
        }
        else if (File.Exists(environmentExampleFileFullPath))
        {
            Console.WriteLine(".env not found. Creating it from .env.example.");
            lines = File.ReadAllLines(environmentExampleFileFullPath).ToList();
        }
        else
        {
            Console.WriteLine(".env not found. Creating a new one.");
            lines = new List<string>();
        }

        string passwordLine = $"{certificatePasswordEnvironmentKey}={password}";
        int passwordLineIndex = lines.FindIndex(IsCertificatePasswordLine);

        if (passwordLineIndex >= 0)
        {
            lines[passwordLineIndex] = passwordLine;
        }
        else
        {
            lines.Add(passwordLine);
        }

        File.WriteAllLines(environmentFileFullPath, lines);

        Console.WriteLine(".env updated successfully.");
    }
    catch (Exception ex)
    {
        Console.WriteLine($"Error updating .env: {ex.Message}");
    }
}

bool IsCertificatePasswordLine(string line)
{
    int separatorIndex = line.IndexOf('=');

    return separatorIndex > 0
        && line[..separatorIndex].Trim().Equals(certificatePasswordEnvironmentKey, StringComparison.OrdinalIgnoreCase);
}

void UpdateAllFirmwareSecretsFiles(string repositoryRootRelative, string caCString)
{
    string repositoryRoot = Path.GetFullPath(Path.Combine(Directory.GetCurrentDirectory(), repositoryRootRelative));

    Console.WriteLine($"\nScanning for firmware projects under: {repositoryRoot}");

    List<string> secretsFiles = FindFirmwareSecretsFiles(repositoryRoot);

    if (secretsFiles.Count == 0)
    {
        Console.WriteLine("No firmware project found (no platformio.ini under the repository root).");
        return;
    }

    foreach (string secretsFile in secretsFiles)
    {
        WriteCaToSecretsFile(secretsFile, caCString);
    }

    Console.WriteLine($"ROOT_CA_CERT updated in {secretsFiles.Count} firmware project(s).");
}

List<string> FindFirmwareSecretsFiles(string repositoryRoot)
{
    var secretsFiles = new List<string>();

    if (!Directory.Exists(repositoryRoot))
        return secretsFiles;

    foreach (string projectFile in EnumerateFilesSkippingBuildOutput(repositoryRoot, "platformio.ini"))
    {
        string? projectDirectory = Path.GetDirectoryName(projectFile);
        if (projectDirectory == null)
            continue;

        secretsFiles.Add(Path.Combine(projectDirectory, "include", "secrets.h"));
    }

    return secretsFiles;
}

IEnumerable<string> EnumerateFilesSkippingBuildOutput(string directory, string fileName)
{
    string[] skippedDirectories = [".git", ".pio", ".vs", ".vscode", ".cache", "bin", "obj", "node_modules"];

    if (skippedDirectories.Contains(Path.GetFileName(directory), StringComparer.OrdinalIgnoreCase))
        yield break;

    string candidate = Path.Combine(directory, fileName);
    if (File.Exists(candidate))
        yield return candidate;

    foreach (string subDirectory in Directory.EnumerateDirectories(directory))
    {
        foreach (string match in EnumerateFilesSkippingBuildOutput(subDirectory, fileName))
            yield return match;
    }
}

void WriteCaToSecretsFile(string secretsFullPath, string caCString)
{
    try
    {
        Console.WriteLine($"Updating secrets.h at: {secretsFullPath}");

        if (!File.Exists(secretsFullPath))
        {
            string? secretsDirectory = Path.GetDirectoryName(secretsFullPath);
            if (secretsDirectory != null)
                Directory.CreateDirectory(secretsDirectory);

            Console.WriteLine("  not found, creating a new one.");
            File.WriteAllText(secretsFullPath, "#pragma once" + Environment.NewLine + Environment.NewLine + caCString);
            return;
        }

        var lines = File.ReadAllLines(secretsFullPath).ToList();
        int removedDefines = RemoveRootCaCertDefines(lines);

        while (lines.Count > 0 && lines[^1].Trim().Length == 0)
            lines.RemoveAt(lines.Count - 1);

        lines.Add(string.Empty);
        lines.AddRange(caCString.Split('\n').Select(line => line.TrimEnd('\r')));

        File.WriteAllLines(secretsFullPath, lines);

        Console.WriteLine(removedDefines > 0
            ? $"  replaced {removedDefines} existing ROOT_CA_CERT define(s)."
            : "  appended ROOT_CA_CERT define.");
    }
    catch (Exception ex)
    {
        Console.WriteLine($"  Error updating {secretsFullPath}: {ex.Message}");
    }
}

int RemoveRootCaCertDefines(List<string> lines)
{
    int removedDefines = 0;

    for (int i = lines.Count - 1; i >= 0; i--)
    {
        if (!lines[i].TrimStart().StartsWith("#define ROOT_CA_CERT"))
            continue;

        int lastLine = i;
        while (lastLine < lines.Count && lines[lastLine].TrimEnd().EndsWith('\\'))
            lastLine++;

        if (lastLine < lines.Count)
            lastLine++;

        lines.RemoveRange(i, lastLine - i);
        removedDefines++;
    }

    return removedDefines;
}

void ImportCaToTrustedRoot(string caCertFile)
{
    try
    {
        string caCertFullPath = Path.Combine(Directory.GetCurrentDirectory(), caCertFile);

        Console.WriteLine($"\nImporting CA certificate into Trusted Root store: {caCertFullPath}");

        RemoveExistingCaFromTrustedRoot("MyLocalCA");

        var process = new Process
        {
            StartInfo = new ProcessStartInfo
            {
                FileName = "powershell",
                Arguments = $"-NoProfile -Command \"Import-Certificate -FilePath '{caCertFullPath}' -CertStoreLocation Cert:\\LocalMachine\\Root\"",
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
                CreateNoWindow = true,
            }
        };

        process.Start();
        string output = process.StandardOutput.ReadToEnd();
        string error = process.StandardError.ReadToEnd();
        process.WaitForExit();

        if (!string.IsNullOrEmpty(output))
            Console.WriteLine(output);
        if (!string.IsNullOrEmpty(error))
            Console.WriteLine(error);

        if (process.ExitCode == 0)
        {
            Console.WriteLine("CA certificate imported into Trusted Root store successfully.");
        }
        else
        {
            Console.WriteLine("Failed to import CA certificate. Run this app as Administrator to import into the Local Machine Trusted Root store.");
        }
    }
    catch (Exception ex)
    {
        Console.WriteLine($"Error importing CA certificate: {ex.Message}");
    }
}

void RemoveExistingCaFromTrustedRoot(string commonName)
{
    try
    {
        Console.WriteLine($"Removing existing '{commonName}' certificates from Trusted Root store...");

        string command = $"Get-ChildItem Cert:\\LocalMachine\\Root | Where-Object {{ $_.Subject -eq 'CN={commonName}' }} | Remove-Item";

        var process = new Process
        {
            StartInfo = new ProcessStartInfo
            {
                FileName = "powershell",
                Arguments = $"-NoProfile -Command \"{command}\"",
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
                CreateNoWindow = true,
            }
        };

        process.Start();
        string output = process.StandardOutput.ReadToEnd();
        string error = process.StandardError.ReadToEnd();
        process.WaitForExit();

        if (!string.IsNullOrEmpty(output))
            Console.WriteLine(output);
        if (!string.IsNullOrEmpty(error))
            Console.WriteLine(error);

        if (process.ExitCode == 0)
        {
            Console.WriteLine($"Existing '{commonName}' certificates removed.");
        }
        else
        {
            Console.WriteLine($"Could not remove existing '{commonName}' certificates. Run this app as Administrator.");
        }
    }
    catch (Exception ex)
    {
        Console.WriteLine($"Error removing existing CA certificates: {ex.Message}");
    }
}

